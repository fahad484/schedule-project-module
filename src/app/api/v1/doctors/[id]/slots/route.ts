import { apiSuccess, apiError } from "@/lib/server-utils";
import { getAvailableSlots } from "@/services/appointment.service";

export async function GET(
  req: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const { id } = await params;
    const { searchParams } = new URL(req.url);
    const date = searchParams.get("date");

    if (!date || !/^\d{4}-\d{2}-\d{2}$/.test(date)) {
      return apiError("Valid date parameter (YYYY-MM-DD) is required", 400);
    }

    const slots = await getAvailableSlots(id, date);
    return apiSuccess(slots);
  } catch (error: unknown) {
    const message =
      error instanceof Error ? error.message : "Internal server error";
    if (message === "Unauthorized") return apiError(message, 401);
    if (message.startsWith("Forbidden")) return apiError(message, 403);
    return apiError(message, 500);
  }
}
